const currencyMap = {
    "en": { symbol: "$", rate: 1 },
    "zh-CN": { symbol: "¥", rate: 7.2 },
    "zh-TW": { symbol: "NT$", rate: 32 },
    "de": { symbol: "€", rate: 0.92 },
    "fr": { symbol: "€", rate: 0.92 },
    "ja": { symbol: "¥", rate: 155 },
    "ko": { symbol: "₩", rate: 1370 },
    "ru": { symbol: "₽", rate: 93 }
};

window.formatPrice = function(priceUSD) {
    const lang = document.documentElement.lang || document.getElementById('lang-switcher')?.value || 'en';
    const mapping = currencyMap[lang] || currencyMap['en'];
    const converted = Math.round(priceUSD * mapping.rate);
    return mapping.symbol + converted;
};

function setLanguage(lang) {
    const dict = window.translations[lang] || window.translations['en'];
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'TITLE') document.title = dict[key];
            else el.innerHTML = dict[key];
        }
    });
    
    // Format static prices on the page
    if (window.formatPrice) {
        document.querySelectorAll('.price-val').forEach(el => {
            const basePrice = parseInt(el.getAttribute('data-base-price'), 10);
            if (!isNaN(basePrice)) {
                el.innerText = window.formatPrice(basePrice);
            }
        });
    }

    if (lang === 'zh-CN' || lang === 'zh-TW') document.body.style.fontFamily = "var(--font-cjk), var(--font-body)";
    else document.body.style.fontFamily = "var(--font-body), var(--font-cjk)";
    
    // Notify other scripts
    window.dispatchEvent(new Event('languageChanged'));
}

// Initialize language from localStorage or default to zh-CN
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('uphoto_lang') || 'zh-CN';
    setLanguage(savedLang);

    const langSwitcher = document.getElementById('lang-switcher');
    if (langSwitcher) {
        langSwitcher.value = savedLang;
        langSwitcher.addEventListener('change', (e) => {
            const newLang = e.target.value;
            localStorage.setItem('uphoto_lang', newLang);
            setLanguage(newLang);
            
            // If reviews exist on this page, re-render them
            if (typeof renderReviewsPage === 'function' && typeof allReviews !== 'undefined' && allReviews.length > 0) {
                renderReviewsPage(typeof currentPage !== 'undefined' ? currentPage : 1);
            }
        });
    }
});


window.t = function(key, params={}) {
    const lang = document.documentElement.lang || document.getElementById('lang-switcher')?.value || 'en';
    let text = window.translations[lang]?.[key] || window.translations['en']?.[key] || key;
    for (const [k, v] of Object.entries(params)) {
        text = text.replace(`{${k}}`, v);
    }
    return text;
};
